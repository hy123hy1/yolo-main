from __future__ import annotations

from datetime import datetime
from typing import Any, Callable, Protocol


class ElectronicSealStoreProtocol(Protocol):
    def claim_runtime(self, channel_id: str, owner_id: str) -> dict[str, Any]: ...
    def list_bound_channel_profiles(self) -> list[dict[str, Any]]: ...
    def list_channel_profiles(self, channel_id: str | None = None) -> list[dict[str, Any]]: ...
    def get_channel_profile(self, channel_id: str) -> dict[str, Any] | None: ...
    def upsert_channel_profile(self, channel_id: str, payload: dict[str, Any]) -> dict[str, Any]: ...
    def list_configs(self, channel_id: str | None = None) -> list[dict[str, Any]]: ...
    def upsert_config(self, channel_id: str, algorithm_type: str, payload: dict[str, Any]) -> dict[str, Any]: ...
    def ensure_default_configs(
        self,
        channel_id: str,
        defaults: list[dict[str, Any]],
        *,
        model_id: str | None,
        preserve_existing: bool,
    ) -> list[dict[str, Any]]: ...
    def prune_channel_configs(self, channel_id: str, allowed_algorithms: set[str]) -> int: ...
    def find_model_by_name(self, name: str) -> dict[str, Any] | None: ...
    def list_upload_jobs(self, statuses: set[str]) -> list[dict[str, Any]]: ...
    def requeue_upload_job(self, job_id: str) -> dict[str, Any] | None: ...
    def list_channels(self) -> list[dict[str, Any]]: ...
    def get_channel(self, channel_id: str) -> dict[str, Any] | None: ...
    def update_channel_snapshot(
        self,
        channel_id: str,
        snapshot_url: str,
        snapshot_path: str,
    ) -> dict[str, Any] | None: ...
    def claim_channel(self, channel_id: str, role: str) -> dict[str, Any]: ...
    def release_channel(self, channel_id: str) -> dict[str, Any]: ...
    def bind_channel_by_stream(self, stream: str) -> dict[str, Any]: ...
    def list_models(self) -> list[dict[str, Any]]: ...
    def get_model(self, model_id: str) -> dict[str, Any] | None: ...
    def invalidate_baseline(self, channel_id: str, algorithm_type: str) -> dict[str, Any]: ...
    def get_state(self, channel_id: str, algorithm_type: str) -> dict[str, Any] | None: ...
    def save_state(self, payload: dict[str, Any]) -> dict[str, Any]: ...
    def online_rates(
        self,
        start_time: datetime,
        end_time: datetime,
        channel_id: str | None = None,
    ) -> list[dict[str, Any]]: ...
    def list_events(self, *args: Any, **kwargs: Any) -> dict[str, Any]: ...
    def get_event(self, event_id: str) -> dict[str, Any] | None: ...
    def update_event(self, event_id: str, payload: dict[str, Any]) -> dict[str, Any] | None: ...
    def get_truck_count(self, channel_id: str) -> dict[str, Any]: ...
    def list_truck_departures(self, channel_id: str, **kwargs: Any) -> dict[str, Any]: ...


class ElectronicSealWorkerProtocol(Protocol):
    source_url: str
    fallback_source_url: str
    configs: list[dict[str, Any]]

    def start(self) -> None: ...
    def stop(self) -> None: ...
    def request_stop(self) -> None: ...
    def wait_and_close(self) -> None: ...
    def update_configs(self, configs: list[dict[str, Any]]) -> None: ...
    def reset_baseline(self, algorithm_type: str) -> None: ...
    def status(self) -> dict[str, Any]: ...


ElectronicSealWorkerFactory = Callable[
    [str, str, list[dict[str, Any]]], ElectronicSealWorkerProtocol
]


__all__ = [
    "ElectronicSealStoreProtocol",
    "ElectronicSealWorkerFactory",
    "ElectronicSealWorkerProtocol",
]
